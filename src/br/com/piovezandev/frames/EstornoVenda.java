    public void estornar() {
        con.conectar();
        try {

            PreparedStatement pst = con.conn.prepareStatement("delete from venda where id_venda =?");
            pst.setString(1, jTidVenda.getText());

            PreparedStatement pstAux = con.conn.prepareStatement("delete from itens_venda_produto where id_venda =?");
            pstAux.setString(1, jTidVenda.getText());

            pst.execute();
            pstAux.execute();

            JOptionPane.showMessageDialog(null, "Estorno Realizado com exito!");
        } catch (SQLException ex) {
            JOptionPane.showMessageDialog(null, "erro : " + ex);
        }
        con.Desconecta();
    }

