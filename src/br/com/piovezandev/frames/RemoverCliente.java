    public final void GerarComboBox() {
        con.conectar();
        try {
            con.executaSQL("select * from cliente order by nome");
            while (con.res.next()) {
                jComboBox1.addItem(con.res.getString("nome"));
            }
        } catch (SQLException ex) {
            Logger.getLogger(AlterarCliente.class.getName()).log(Level.SEVERE, null, ex);
        }
        con.Desconecta();
    }

    public void excluir() {
        con.conectar();

        try {
            String AUX = (String) jComboBox1.getSelectedItem();
            PreparedStatement pst = con.conn.prepareStatement("delete from cliente where nome=?");
            pst.setString(1, AUX);
            pst.execute();

            JOptionPane.showMessageDialog(null, "Cadastro Removido");
        } catch (SQLException ex) {
            JOptionPane.showMessageDialog(null, "erro : " + ex);
        }
        con.Desconecta();
    }

