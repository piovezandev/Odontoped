    public boolean acessoRelatorio(String tipoRelatorio) {
        ConexaoJDBC con = new ConexaoJDBC();
        con.conectar();
        try {
            if (JTusuario.getText().equals("") || JTsenha.getText().equals("")) {
                JOptionPane.showMessageDialog(null, "Nenhum Campo pode estar vazio!");
            } else {
                con.executaSQL("select * from login where nome like '%" + JTusuario.getText() + "%' and senha like '%" + JTsenha.getText() + "%'");

                while (con.res.next()) {
                    switch (tipoRelatorio) {
                        case "relatorio_dentista":
                            new Relatorios().RelatorioCliente();
                            break;
                        case "relatorio_conferencia":
                            new RelatorioConferencia().setVisible(true);
                            break;
                        case "relatorio_data":
                            new RelatorioData().setVisible(true);
                            break;
                        case "relatorio_descritivo":
                            new Relatorios().RelatorioDescritivo();
                            break;
                        case "relatorio_mensal_nome":
                            new RelatorioMensalNome().setVisible(true);
                            break;
                        case "relatorio_nota_fiscal":
                            new RelatorioNotaFiscal().setVisible(true);
                            break;
                        case "relatorio_produto":
                            new Relatorios().RelatorioProduto();
                            break;
                        case "relatorio_item_comissionado":
                            new RelatorioProdutosComissinados().setVisible(true);
                            break;
                        case "relatorio_totalizador_mensal":
                            new RelatorioTotalizadorPorMes().setVisible(true);
                            break;
                        case "relatorio_nome":
                            new RelatorioNome().setVisible(true);
                            break;

                    }
                    dispose();
                    return true;

                }

            }

        } catch (SQLException e) {
            JOptionPane.showMessageDialog(null, "Usuario ou senha invalidos!");
            System.out.println("erro");
        }
        return false;
    }
