    public void verifica() {

        ano = (String) jComboBoxAno.getSelectedItem();
        mes = (String) jComboBoxMes.getSelectedItem();

        switch (mes) {
            case "Janeiro":
                aux = 1;
                break;
            case "Fevereiro":
                aux = 2;
                break;
            case "Março":
                aux = 3;
                break;
            case "Abril":
                aux = 4;
                break;
            case "Maio":
                aux = 5;
                break;
            case "Junho":
                aux = 6;
                break;
            case "Julho":
                aux = 7;
                break;
            case "Agosto":
                aux = 8;
                break;
            case "Setembro":
                aux = 9;
                break;
            case "Outubro":
                aux = 10;
                break;
            case "Novembro":
                aux = 11;
                break;
            case "Dezembro":
                aux = 12;
                break;
            default:
                JOptionPane.showMessageDialog(null, "Mes Inválido");

        }
    }


    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
        try {

            verifica();
            StringBuilder sql = new StringBuilder();

            sql.append("select v.nome_cli, sum(v.valor_venda) as total, " + ano + " as ano, \n");
            sql.append("case when month(STR_TO_DATE(v.data_venda, '%d/%m/%Y')) = 01 then 'Janeiro' \n");
            sql.append("when month(STR_TO_DATE(v.data_venda, '%d/%m/%Y')) = 02 then 'Fevereiro' \n");
            sql.append("when month(STR_TO_DATE(v.data_venda, '%d/%m/%Y')) = 03 then 'Março' \n");
            sql.append("when month(STR_TO_DATE(v.data_venda, '%d/%m/%Y')) = 04 then 'Abril' \n");
            sql.append("when month(STR_TO_DATE(v.data_venda, '%d/%m/%Y')) = 05 then 'Maio' \n");
            sql.append("when month(STR_TO_DATE(v.data_venda, '%d/%m/%Y')) = 06 then 'Junho' \n");
            sql.append("when month(STR_TO_DATE(v.data_venda, '%d/%m/%Y')) = 07 then 'Julho' \n");
            sql.append("when month(STR_TO_DATE(v.data_venda, '%d/%m/%Y')) = 08 then 'Agosto' \n");
            sql.append("when month(STR_TO_DATE(v.data_venda, '%d/%m/%Y')) = 09 then 'Setembro' \n");
            sql.append("when month(STR_TO_DATE(v.data_venda, '%d/%m/%Y')) = 10 then 'Outubro' \n");
            sql.append("when month(STR_TO_DATE(v.data_venda, '%d/%m/%Y')) = 11 then 'Novembro'  \n");
            sql.append("when month(STR_TO_DATE(v.data_venda, '%d/%m/%Y')) = 12 then 'Dezembro'   end as mes \n");
            sql.append("from venda v where  \n");
            sql.append("month(STR_TO_DATE( v.data_venda, '%d/%m/%Y')) = " + aux + " \n");
            sql.append("and year(STR_TO_DATE(v.data_venda, '%d/%m/%Y')) = " + ano + " \n");
            sql.append("and v.status_venda <>  \"aberta\" \n");
            sql.append("group by v.nome_cli \n");
            sql.append("order by v.nome_cli \n");

            con.conectar();
            con.executaSQL(sql.toString());
            JRResultSetDataSource relatResul = new JRResultSetDataSource(con.res);
            JasperPrint jprint = JasperFillManager.fillReport("c:/Odontoped/relatorios/Relatorio totalizador mensal.jasper", new HashMap(), relatResul);
            JasperViewer jview = new JasperViewer(jprint, false);
            jview.setVisible(true);
            jview.toFront();

        } catch (JRException ex) {
            JOptionPane.showMessageDialog(null, "erro " + ex.getMessage());
        }
        con.Desconecta();
    }//GEN-LAST:event_jButton2ActionPerformed

