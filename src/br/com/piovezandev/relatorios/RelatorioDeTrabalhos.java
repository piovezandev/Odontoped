    public final void gerarComboBoxFuncionarios() {
        con.conectar();

        try {
            con.executaSQL("select * from funcionario order by nome");
            while (con.res.next()) {
                jcbxFuncionario.addItem(con.res.getString("nome"));
            }
        } catch (SQLException ex) {
            Logger.getLogger(RelatorioDeTrabalhos.class.getName()).log(Level.SEVERE, null, ex);
        }
        con.Desconecta();
    }

    public boolean geraRelatorioOrdemServico() {
        con.conectar();

        FileWriter writer;

        String sql = "select * from venda inner join itens_venda_produto on \n"
                + " venda.id_venda=itens_venda_produto.id_venda inner join \n"
                + "produto on itens_venda_produto.id_produto = produto.codigo \n"
                + "where funcionario='" + jcbxFuncionario.getSelectedItem().toString() + "' and data_venda between '" + dataInicio.getText() + "' and '" + dataFim.getText() + "' and  venda.status_venda = 'aberta' ";

        try {
            con.executaSQL(sql);

            if (!con.res.isBeforeFirst()) {
                JOptionPane.showMessageDialog(null, "Não foi encontrado registros no filtro selecionado");
                return false;
            } else {
                writer = new FileWriter("C:/Odontoped/temp/" + jcbxFuncionario.getSelectedItem().toString() + ".txt", false); // com o parâmetro true você informa que não deve sobrescrever e sim mesclar.
                PrintWriter out = new PrintWriter(writer);
                out.write("Colaborador: " + jcbxFuncionario.getSelectedItem().toString().trim() + "\n");
                out.write("Agendamento do dia:" + dataInicio.getText() + " ao dia:" + dataFim.getText() + "\n");
                out.write("\n\nItens: \n");

                while (con.res.next()) {

                    out.write("*** " + con.res.getString("produto") + " ***" + "\n");

                    out.write(con.res.getString("cor").length() > 0 ? "\nCor: " + con.res.getString("cor") : "");
                    out.write(con.res.getString("adesivo").length() > 0 ? "\nAdesivo: " + con.res.getString("adesivo") : "");
                    out.write(con.res.getString("nome_aparelho").equals("S") ? "\nNome no aparelho: Sim " : "\nNome no aparelho: Nao");
                    out.write(con.res.getString("glitter_aparelho").equals("S") ? "\nGlitter no aparelho: Sim " : "\nGlitter no aparelho: Nao");
                    out.write(con.res.getString("descricao").length() > 0 ? "\nDescricao: " + con.res.getString("descricao") : "");
                    out.write("\n\nDentista: " + con.res.getString("nome_cli"));
                    out.write(con.res.getString("paciente").length() > 0 ? "\nPaciente: " + con.res.getString("codigo_os") + " - " + con.res.getString("paciente") : "\nPaciente: " + con.res.getString("codigo_os") + " - " + "sem nome");

                    out.write("\n\n");

                }
                out.flush();
                out.close();
            }
            return true;

        } catch (IOException ex) {
            JOptionPane.showMessageDialog(null, "erro:" + ex.getMessage());
            return false;
        } catch (SQLException ex) {
            JOptionPane.showMessageDialog(null, "Nenhum dado foi encontrado");
            return false;
        }

    }

    public void emiteCupom() {
        try {
            java.io.InputStream is = new FileInputStream("C:/Odontoped/temp/" + jcbxFuncionario.getSelectedItem().toString() + ".txt");
            Scanner sc = new Scanner(is);
            FileOutputStream fs = new FileOutputStream("//localhost/POS58");
            PrintStream ps = new PrintStream(fs);

            while (sc.hasNextLine()) {
                String linhas = sc.nextLine();
                ps.println(linhas);
            }
            fs.close();
        } catch (IOException ex) {
            JOptionPane.showMessageDialog(null, "Erro encontrado ao imprimir comanda.");
        } finally {
            File file = new File("C:/Odontoped/temp/" + jcbxFuncionario.getSelectedItem().toString() + ".txt");
            file.delete();
        }
    }


